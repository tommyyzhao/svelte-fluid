<script lang="ts">
	import { onMount } from 'svelte';
	import { LabSession } from './LabSession.js';
	import { createThreadStudy, type ThreadStudyExperiment, type ThreadStudyMode } from './thread-study.js';
	let { mode, ratio, feed, spacing, turns, available = $bindable(false), running = $bindable(false), count = $bindable(0), full = $bindable(false), canFeed = $bindable(false) }: {
		mode: ThreadStudyMode; ratio: number; feed: number; spacing: number; turns: number;
		available?: boolean; running?: boolean; count?: number; full?: boolean; canFeed?: boolean;
	} = $props();
	let host: HTMLDivElement, canvas: HTMLCanvasElement;
	let session: LabSession | undefined, model: ThreadStudyExperiment | undefined;
	let ready = $state(false), error = $state(''), reduced = $state(false), visible = $state(true), pageVisible = $state(true);
	$effect(() => { available = ready && !error; });
	$effect(() => { canFeed = available && !reduced && visible && pageVisible && !full && mode === 'deposition'; });
	$effect(() => { const selected = mode; model?.setMode(selected); if (session && !session.state.paused) session.pause(); session?.invalidate(); });
	$effect(() => { const settings = { ratio, feed, spacing, turns }; model?.setControls(settings); session?.invalidate(); });
	export function start() {
		if (!canFeed) return;
		model?.setFeeding(true); if (session?.state.paused) session.pause();
	}
	export function pause() {
		model?.setFeeding(false); if (session && !session.state.paused) session.pause();
		if (visible && !document.hidden) session?.invalidate();
	}
	export function sample() { if (available && mode === 'deposition') { pause(); model?.depositSample(1.5); session?.invalidate(); } }
	export function reset() { if (available) { pause(); model?.reset(); session?.invalidate(); } }
	onMount(() => {
		let disposed = false;
		pageVisible = !document.hidden;
		const motion = matchMedia('(prefers-reduced-motion: reduce)'); reduced = motion.matches;
		function resize() { const bounds = canvas.getBoundingClientRect(); session?.resize(bounds.width, bounds.height); }
		function preferences() { reduced = motion.matches; if (reduced) pause(); }
		function visibility() { pageVisible = !document.hidden; if (!pageVisible) pause(); else session?.invalidate(); }
		const sizes = new ResizeObserver(resize); sizes.observe(host);
		const intersection = new IntersectionObserver(([entry]) => { visible = entry.isIntersecting; if (!visible) pause(); else session?.invalidate(); }); intersection.observe(host);
		motion.addEventListener('change', preferences); document.addEventListener('visibilitychange', visibility);
		void LabSession.create(canvas, (state) => { if (!disposed) { ready = state.ready; if (state.error) error = state.error; } }, 'premultiplied').then(async (created) => {
			if (disposed) { created.dispose(); return; }
			session = created; resize();
			await session.load(async (device, format) => {
				const candidate = await createThreadStudy(device, format, (state) => {
					if (disposed) return;
					running = state.feeding; count = state.count; full = state.full;
					if (state.error) error = state.error;
					if ((state.full || state.error) && session && !session.state.paused) queueMicrotask(() => { if (!disposed && session && !session.state.paused) pause(); });
				});
				if (!disposed) { model = candidate; candidate.setMode(mode); candidate.setControls({ ratio, feed, spacing, turns }); }
				return candidate;
			});
			if (!disposed) pause();
		}).catch((reason) => { if (!disposed) error = String(reason); });
		return () => { disposed = true; sizes.disconnect(); intersection.disconnect(); motion.removeEventListener('change', preferences); document.removeEventListener('visibilitychange', visibility); session?.dispose(); };
	});
</script>

<div class="thread-surface" bind:this={host} role="img" aria-label={mode === 'braid' ? 'Three smooth metallic strands in an authored over-and-under braid with real depth separation.' : 'A continuous deposited liquid-thread trace generated by a reduced contact-point model on a moving belt.'} data-mode={mode} data-count={count} data-full={full} data-running={running}>
	<canvas bind:this={canvas} class:unavailable={!ready || Boolean(error)} aria-hidden="true"></canvas>
	<p class="status" role="status">{error ? 'Static study — WebGPU unavailable. ' + error : !ready ? 'Preparing native thread geometry…' : mode === 'braid' ? 'Authored over / under · real depth · no friction solver' : full ? 'History full. Feed stopped; start a new thread to continue.' : reduced ? 'Still trace · use Add a short sample with reduced motion' : running ? 'Depositing · the belt carries the earlier material' : 'Trace retained · use Start feed or Add a short sample'}</p>
</div>

