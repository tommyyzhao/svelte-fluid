	ignored, with a one-time console warning.
</p>

<p>
	Velocity values are in pixels per frame and written directly to the splat shader uniform.
	Unlike pointer-driven splats, these are <strong>not</strong> multiplied by <code>splatForce</code>.
	Pick the absolute magnitude you want. Typical values range from 100 (gentle) to 1000 (forceful).
</p>

<h3>randomSplats(count)</h3>

<p>Push N additional random splats onto the splat queue. Colors are generated by the engine's internal color function.</p>

<p>
	The queued backlog is capped at 64 and the engine consumes at most 16 per frame, so repeated calls
	saturate instead of growing without bound. Non-finite or negative counts are ignored.
</p>

