<h2>FluidEngine (Advanced)</h2>

<p>
	For advanced users who need framework-agnostic fluid simulation, the <code>FluidEngine</code>
	class is exported from the package root. It is the WebGL engine that powers the
	<code>&lt;Fluid&gt;</code> component, but it has no Svelte dependency.
</p>

<pre><code>import {LB} FluidEngine {RB} from 'svelte-fluid';</code></pre>

<p>
	The engine is constructed with a <code>canvas</code> element and a <code>config</code> object
	matching the <code>FluidConfig</code> interface. It exposes the same <code>splat()</code>,
	<code>randomSplats()</code>, <code>pause()</code>, <code>resume()</code>,
	<code>isPaused</code>, and <code>getPerformanceState()</code> API as
	<code>FluidHandle</code>, plus additional methods:
</p>

<ul>
	<li><code>setConfig(config)</code> — update configuration at runtime (respects the 4-bucket system)</li>
	<li><code>dispose()</code> — free all GPU resources (textures, framebuffers, programs). The WebGL context is left intact for potential reuse.</li>
</ul>

<h2>Experimental entry</h2>

<p>
	<code>svelte-fluid/experimental</code> exposes unstable engine surfaces: a free-surface liquid engine and a caller-clocked air engine.
	<strong>No semver promise:</strong> any minor release may change or remove them.
</p>

<ul>
	<li><code>LiquidEngine</code> — a free-surface PIC/FLIP liquid on its own WebGL2 canvas, with terrain, three pigment species, exact sensor counts and drains (needs <code>EXT_color_buffer_float</code> and <code>EXT_float_blend</code>). Its scene, tick and sensor types are exported alongside.
		Terrain uses <code>Cell.Air</code> (0) and <code>Cell.Solid</code> (1). Values 2 to 6 are also solid and free for caller tags. The older <code>AIR</code>, <code>STONE</code>, <code>LOAM</code>, <code>INK</code>, <code>GATE</code>, <code>VINE</code> and <code>ROOT</code> constants are <code>@deprecated</code>.
		Types: <code>CellRect</code>, <code>CellVec</code>, <code>SpeciesCounts</code>, <code>LiquidSpecies</code>, <code>LiquidWind</code>, <code>LiquidRenderOptions</code>, <code>LiquidFill</code>, <code>LiquidRegion</code>, <code>LiquidEmit</code>. The older <code>Rect</code>, <code>Vec</code>, <code>Counts</code>, <code>Species</code>, <code>Wind</code> and <code>RenderOptions</code> names are <code>@deprecated</code>.</li>
	<li><code>createSteppedFluidEngine(options)</code> — a <code>FluidEngine</code> driven by your clock: <code>advance(steps, dt)</code>, <code>renderOnce()</code>, in-place <code>resize(w, h)</code>, and nonblocking air velocity readback with <code>queueVelocitySnapshot(tick, w, h)</code> / <code>pollVelocitySnapshot()</code>. Pass a snapshot to <code>LiquidEngine.step({LB} wind {RB})</code> so air deflects falling liquid. It has no <code>pause()</code>, <code>resume()</code> or <code>isPaused</code>: drive it with <code>advance</code> and <code>renderOnce</code>.</li>
</ul>

<p>
	Coordinates differ between the two. <code>VelocitySnapshot</code> is normalized units per second, y up, bottom row first.
	<code>LiquidTick.wind</code> is cells per second, y down, top row first. To convert, use <code>vx = width · ux</code>,
	<code>vy = −height · uy</code>, and reverse the row order.
</p>

<pre><code>import {LB} LiquidEngine, createSteppedFluidEngine {RB} from 'svelte-fluid/experimental';</code></pre>

<p>
	Architecture invariant: the engine never imports Svelte. It is fully framework-agnostic and
	could be used with React, vanilla JS, or any other framework. The Svelte component is a thin
	wrapper that handles lifecycle, sizing, and prop reactivity.
</p>
